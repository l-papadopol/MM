#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
APP_NAME="MadModem"
VERSION="$(cat "$ROOT_DIR/MADMODEM_VERSION.txt" 2>/dev/null || echo dev)"
INSTALL_DIR="${MADMODEM_LINUX_INSTALL_DIR:-$ROOT_DIR/dist/linux}"
OUT_DIR="${MADMODEM_PACKAGE_OUT_DIR:-$ROOT_DIR/dist/packages}"
ARCH="${MADMODEM_LINUX_ARCH:-x86_64}"
PLATFORM="${MADMODEM_LINUX_PLATFORM:-Linux}"
PACKAGE_NAME="${APP_NAME}-${VERSION}-${PLATFORM}-${ARCH}"
PACKAGE_DIR="$OUT_DIR/$PACKAGE_NAME"
TAR_PATH="$OUT_DIR/$PACKAGE_NAME.tar.gz"
ZIP_PATH="$OUT_DIR/$PACKAGE_NAME.zip"

if [[ ! -x "$INSTALL_DIR/bin/$APP_NAME" ]]; then
    echo "ERROR: Linux executable not found: $INSTALL_DIR/bin/$APP_NAME" >&2
    exit 1
fi

rm -rf "$PACKAGE_DIR"
mkdir -p "$PACKAGE_DIR"
cp -a "$INSTALL_DIR/." "$PACKAGE_DIR/"
# A portable archive must not accidentally inherit installer path semantics or
# data from a reused local staging directory.
for user_file in settings.mad logbook.adi; do
    if [[ -e "$PACKAGE_DIR/bin/$user_file" ]]; then
        echo "ERROR: refusing to distribute user data: $user_file" >&2
        exit 1
    fi
done
rm -f "$PACKAGE_DIR/bin/managed-install.flag"

# User-facing documentation/legal files for the binary package.
for f in README.md RELEASE_NOTES.md CHANGELOG.md LICENSE.md COPYING AUTHORS.md THIRD_PARTY_NOTICES.md TRANSLATION_AUDIT.md; do
    [[ -f "$ROOT_DIR/$f" ]] && cp -f "$ROOT_DIR/$f" "$PACKAGE_DIR/"
done

# Runtime data is resolved from QCoreApplication::applicationDirPath(), so keep
# it next to the executable.  Do not duplicate rtty_rules at package root.
[[ -f "$ROOT_DIR/cty.csv" ]] && cp -f "$ROOT_DIR/cty.csv" "$PACKAGE_DIR/bin/cty.csv"
if [[ ! -f "$ROOT_DIR/rtty_rules" ]]; then
    echo "ERROR: RTTY contest rules not found in source tree: $ROOT_DIR/rtty_rules" >&2
    exit 1
fi
cp -f "$ROOT_DIR/rtty_rules" "$PACKAGE_DIR/bin/rtty_rules"
if [[ ! -f "$ROOT_DIR/cw_rules" ]]; then
    echo "ERROR: CW contest rules not found in source tree: $ROOT_DIR/cw_rules" >&2
    exit 1
fi
cp -f "$ROOT_DIR/cw_rules" "$PACKAGE_DIR/bin/cw_rules"
if [[ ! -f "$PACKAGE_DIR/bin/rtty_rules" ]]; then
    echo "ERROR: Linux package is missing bin/rtty_rules" >&2
    exit 1
fi
if [[ ! -f "$PACKAGE_DIR/bin/cw_rules" ]]; then
    echo "ERROR: Linux package is missing bin/cw_rules" >&2
    exit 1
fi

python3 "$ROOT_DIR/scripts/bundle_linux_runtime.py" "$PACKAGE_DIR"

cat > "$PACKAGE_DIR/RUN_LINUX.txt" <<TXT
MadModem Linux package
======================

Run:
  ./AppRun

Version: $VERSION
Architecture: $ARCH
Build platform: $PLATFORM
Generated by: scripts/package_linux_github.sh

Extract this archive into a writable folder and run AppRun (or bin/MadModem).
Qt5, Hamlib, the required Qt plugins/QML modules and their runtime libraries
are included. No separate Qt or Hamlib installation is needed.
Use the build matching your distribution; the host provides glibc, graphics
drivers, a desktop session and its audio server. This is not a universal AppImage.
Do not run MadModem.bin directly: the launcher selects the bundled libraries.
See runtime-manifest.json and runtime-licenses for bundled component details.
Keep settings.mad, ADIF logbooks and recordings when replacing a portable copy.
TXT

cp -f "$PACKAGE_DIR/RUN_LINUX.txt" "$PACKAGE_DIR/BUILD_INFO.txt"

chmod +x "$PACKAGE_DIR/bin/$APP_NAME" || true
rm -f "$TAR_PATH"
mkdir -p "$OUT_DIR"
tar -C "$OUT_DIR" -czf "$TAR_PATH" "$PACKAGE_NAME"

python3 - "$PACKAGE_DIR" "$ZIP_PATH" <<'PYZIP'
from pathlib import Path
import sys, zipfile
root = Path(sys.argv[1])
with zipfile.ZipFile(sys.argv[2], 'w', zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
    for file in sorted(root.rglob('*')):
        if file.is_file():
            archive.write(file, root.name + '/' + file.relative_to(root).as_posix())
PYZIP

printf 'Linux packages complete:\n  %s\n  %s\n' "$TAR_PATH" "$ZIP_PATH"
